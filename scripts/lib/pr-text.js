// Pure logic for the scheduled lineup job's pull request: a title and a markdown body from the old and new
// pipeline state. No I/O. All text that comes from the festival API or Last.fm is untrusted: it is made inert
// (no @mentions, no HTML) before it goes into the body.

const MAX_BODY = 60000; // GitHub's limit is 65536 characters
const MAX_LISTED = 40;

/** Make external text inert in a GitHub comment/PR body: no @mentions, no raw HTML. */
export function sanitize(text) {
  return String(text).replace(/</g, '&lt;').replace(/@/g, '@\u200b');
}

const active = (state) => (state?.artists ?? []).filter((a) => !a.removed);
const eventCount = (state) => (state?.schedule?.events ?? []).length;
const unverifiedCount = (lineup) => (lineup?.artists ?? []).filter((a) => a.unverified).length;
const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;

/** @returns {{added: string[], removed: string[], renamed: {from: string, to: string}[]}} compared by artist number `n` */
export function diffArtists(oldState, newState) {
  const before = new Map(active(oldState).map((a) => [a.n, a]));
  const after = new Map(active(newState).map((a) => [a.n, a]));
  const added = [];
  const removed = [];
  const renamed = [];
  for (const [n, a] of after) {
    const b = before.get(n);
    if (!b) added.push(a.name);
    else if (b.name !== a.name) renamed.push({ from: b.name, to: a.name });
  }
  for (const [n, b] of before) if (!after.has(n)) removed.push(b.name);
  return { added, removed, renamed };
}

/**
 * Sections of review.md worth a human's attention: the lineup source (always) and every other section whose
 * heading count is not zero, except those the summary already covers (added, removed, renamed, id sources, schedule).
 */
export function reviewSections(review) {
  if (!review) return [];
  const parts = review.split(/^(?=## )/m).filter((p) => p.startsWith('## '));
  const covered = /^## (Spotify ids by source|Added|Removed|Renamed|Schedule)/;
  return parts
    .filter((p) => {
      const heading = p.split('\n', 1)[0];
      if (covered.test(heading)) return false;
      if (/^## Lineup source/.test(heading)) return true;
      const m = heading.match(/\((\d+)\)/);
      return !m || Number(m[1]) > 0;
    })
    .map((p) => p.trimEnd());
}

function listNames(label, names) {
  if (names.length === 0) return [];
  const shown = names.slice(0, MAX_LISTED).map((n) => `- ${sanitize(n)}`);
  if (names.length > MAX_LISTED) shown.push(`- ... and ${names.length - MAX_LISTED} more`);
  return [`**${label} (${names.length})**`, ...shown, ''];
}

/**
 * @param {{oldState?: object, newState: object, oldLineup?: object, newLineup?: object, review?: string}} input
 * @returns {{title: string, body: string}}
 */
export function summarize({ oldState, newState, oldLineup, newLineup, review }) {
  const { added, removed, renamed } = diffArtists(oldState, newState);
  const ev0 = eventCount(oldState);
  const ev1 = eventCount(newState);
  const unv0 = unverifiedCount(oldLineup);
  const unv1 = unverifiedCount(newLineup);
  const year = newState?.year ?? '';

  const bits = [];
  if (added.length) bits.push(`+${plural(added.length, 'artist')}`);
  if (removed.length) bits.push(`-${plural(removed.length, 'artist')}`);
  if (renamed.length) bits.push(`${renamed.length} renamed`);
  if (unv1 !== unv0) bits.push(`unverified ${unv0} -> ${unv1}`);
  if (ev0 === 0 && ev1 > 0) bits.push(`schedule published (${plural(ev1, 'event')})`);
  else if (ev1 !== ev0) bits.push(`events ${ev0} -> ${ev1}`);
  const title = `Lineup update${year ? ` ${year}` : ''}: ${bits.length ? bits.join(', ') : 'data refreshed, no artist changes'}`;

  const lines = ['## Summary', ''];
  lines.push(`- Artists on the lineup: ${active(oldState).length} -> ${active(newState).length}`);
  lines.push(`- Added ${added.length}, removed ${removed.length}, renamed ${renamed.length}`);
  lines.push(`- Matches flagged unverified: ${unv0} -> ${unv1}`);
  lines.push(`- Schedule events: ${ev0} -> ${ev1}`);
  lines.push('');
  lines.push(...listNames('Added', added));
  lines.push(...listNames('Removed', removed));
  lines.push(...listNames('Renamed', renamed.map((r) => `${r.from} -> ${r.to}`)));

  lines.push('## Needs a human look', '');
  lines.push('From `data/' + year + '/review.md` as generated by this run. Sections with nothing in them are left out.', '');
  const sections = reviewSections(review);
  if (sections.length === 0) lines.push('_No review report was found._', '');
  for (const s of sections) lines.push(sanitize(s).replace(/^## /, '### '), '');

  lines.push('## Correcting a match', '');
  lines.push(`Do not edit the generated files by hand. Add or change an entry in \`data/${year}/overrides.json\`, then run \`npm run lineup:build\` and commit. The job always respects overrides. Note this branch is rebuilt from \`main\` on every run, so merge the overrides on \`main\` first, or push them to \`main\` through a separate pull request.`, '');
  lines.push('## Merging', '');
  lines.push('Safe to merge when both required checks, `check` and `Cloudflare Pages`, are green.', '');
  lines.push('_Opened by the scheduled lineup workflow. Replaced in place on each run while open._');

  let body = lines.join('\n');
  if (body.length > MAX_BODY) body = body.slice(0, MAX_BODY) + '\n\n_(truncated; see `data/' + year + '/review.md` in this branch)_';
  return { title, body };
}
